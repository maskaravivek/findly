// Records one live SearchAPI response per shopping engine for q="cordless drill" into
// packages/test-fixtures/src/searchapi/recorded/<engine>.json (and a generated <engine>.ts const, because the
// workspace tsconfig has no resolveJsonModule). One attempt per engine, no retries: five calls, five credits.
//   node --env-file=../../.env --import tsx scripts/record-searchapi-fixtures.ts            # record + generate
//   node --import tsx scripts/record-searchapi-fixtures.ts --ts-only                        # regenerate .ts from saved JSON
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const OUT_DIR = fileURLToPath(new URL("../../../packages/test-fixtures/src/searchapi/recorded/", import.meta.url));
const ENDPOINT = "https://www.searchapi.io/api/v1/search";
const QUERY = "cordless drill";
const MAX_ITEMS = 6;
const ENGINES: Record<string, Record<string, string>> = {
  amazon_search: { amazon_domain: "amazon.com", delivery_country: "US" },
  walmart_search: {},
  home_depot_search: {},
  bestbuy_search: {},
  google_shopping: { gl: "us" }
};

const secretKey = (key: string) => /api[_-]?key|authorization|token|secret/i.test(key);
const stripApiKeyParam = (value: string) => value.replace(/([?&])api_key=[^&#]*(&?)/gi, (_m, sep: string, amp: string) => (amp ? sep : ""));

/** Removes key-like fields anywhere and api_key query params inside any string. */
function scrub(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(scrub);
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).filter(([k]) => !secretKey(k)).map(([k, v]) => [k, scrub(v)]));
  }
  return typeof value === "string" ? stripApiKeyParam(value) : value;
}

function sanitize(raw: Record<string, unknown>): Record<string, unknown> {
  const out: Record<string, unknown> = { ...raw };
  const meta = out.search_metadata;
  if (meta && typeof meta === "object") out.search_metadata = Object.fromEntries(Object.entries(meta).filter(([k]) => !/url/i.test(k)));
  const params = out.search_parameters;
  if (params && typeof params === "object") { const { api_key: _drop, ...rest } = params as Record<string, unknown>; out.search_parameters = rest; }
  for (const [k, v] of Object.entries(out)) if (Array.isArray(v)) out[k] = v.slice(0, MAX_ITEMS);
  return scrub(out) as Record<string, unknown>;
}

const camel = (engine: string) => engine.replace(/_([a-z])/g, (_m, c: string) => c.toUpperCase());
async function writeTs(engine: string) {
  const json = await readFile(`${OUT_DIR}${engine}.json`, "utf8");
  const body = `// GENERATED by apps/api/scripts/record-searchapi-fixtures.ts from ${engine}.json. Do not edit by hand.\n` +
    `export const ${camel(engine)}Recorded = ${json.trimEnd()};\n`;
  await writeFile(`${OUT_DIR}${engine}.ts`, body);
}

async function record(engine: string, extra: Record<string, string>, apiKey: string) {
  const url = new URL(ENDPOINT);
  url.searchParams.set("engine", engine);
  url.searchParams.set("q", QUERY);
  for (const [k, v] of Object.entries(extra)) url.searchParams.set(k, v);
  const res = await fetch(url, { headers: { Authorization: `Bearer ${apiKey}`, Accept: "application/json" }, signal: AbortSignal.timeout(90_000) });
  if (!res.ok) { await res.body?.cancel(); throw new Error(`HTTP ${res.status}`); }
  const json = sanitize((await res.json()) as Record<string, unknown>);
  const text = JSON.stringify(json, null, 2) + "\n";
  if (text.includes(apiKey)) throw new Error("response still contains the API key after sanitising; not saved");
  await writeFile(`${OUT_DIR}${engine}.json`, text);
  await writeTs(engine);
  return Buffer.byteLength(text);
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  if (process.argv.includes("--ts-only")) { for (const engine of Object.keys(ENGINES)) await writeTs(engine); console.log("Regenerated .ts fixtures"); return; }
  const apiKey = process.env.SEARCHAPI_API_KEY;
  if (!apiKey) throw new Error("SEARCHAPI_API_KEY is not set (run with --env-file=../../.env)");
  let failed = 0;
  for (const [engine, extra] of Object.entries(ENGINES)) {
    try { console.log(`${engine}: saved ${await record(engine, extra, apiKey)} bytes`); }
    catch (error) { failed++; console.error(`${engine}: ${error instanceof Error ? error.message : "failed"}`); }
  }
  if (failed) process.exitCode = 1;
}

await main();
